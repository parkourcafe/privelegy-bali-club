-- артефакт усечения полуночи.
--
-- Два из них, ecosfera-yoga-canggu-canggu и green-spot-cafe, уже были
-- разобраны и ОТКЛОНЕНЫ 2026-08-04 — см. блок «ОТКЛОНЕНО» в
