-- повторную запись и не тронула то, что уже опубликовано.
--
-- Два заведения противоречат сами себе: у green-spot-cafe и
-- the-nini-restaurant-12 в why_its_here стоит «open daily 7:00am-11:00pm»,
-- а в колонке часов — 14:00. Обе строки видны на карточке.
--
-- ── ПОЧЕМУ null, А НЕ ИСПРАВЛЕНИЕ ─────────────────────────────────────
--
-- Правильных часов у нас нет ни для одной из пяти строк. Проза в
-- why_its_here не является источником: она сама не проверена. Ставить
