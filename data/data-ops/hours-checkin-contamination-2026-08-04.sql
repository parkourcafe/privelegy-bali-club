--
-- Пустое поле не отрисовывается — это верное поведение (гардрейл №10:
-- неизвестное остаётся null). Опубликованное «открыто с 14:00» для
-- утреннего кафе — это неверное обещание, по которому человек приходит
-- к закрытой двери и не сообщает об этом никому.
