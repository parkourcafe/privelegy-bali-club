-- Строки остаются в списке на сбор часов: их закроет обычный прогон по
-- официальному источнику заведения.

-- ── DRY RUN — одна строка, откат ──────────────────────────────────────
begin;
update venues
set opening_hours = null
where slug = 'green-spot-cafe'
  and status = 'active'
  and publication_status = 'published'
  and opening_hours = 'Mo-Su 14:00-23:59';
-- ожидается: UPDATE 1
rollback;


-- ── APPLY ─────────────────────────────────────────────────────────────
-- ожидается: UPDATE 5
update venues
set opening_hours = null
where slug in (
  'casa-blanca-bali',
  'ecosfera-yoga-canggu-canggu',
  'green-spot-cafe',
  'satoshi',
  'the-nini-restaurant-12'
)
  and status = 'active'
  and publication_status = 'published'
  -- Условие на само значение: если строку уже починили вручную,
  -- повторный запуск её не тронет.
  and opening_hours = 'Mo-Su 14:00-23:59';


-- ── VERIFY ────────────────────────────────────────────────────────────
-- ожидается: 0
select count(*) from venues where opening_hours = 'Mo-Su 14:00-23:59';

-- Контроль, что не задето лишнее: ожидается 5 строк с opening_hours is null.
select slug, opening_hours from venues
where slug in ('casa-blanca-bali','ecosfera-yoga-canggu-canggu','green-spot-cafe',
               'satoshi','the-nini-restaurant-12')
order by slug;


