-- rollback;

-- ── APPLY ─────────────────────────────────────────────────────────────
-- ожидалось: UPDATE 5 — получено 5
update venues as v
set latitude = d.lat, longitude = d.lng, last_verified_at = '2026-08-04'
from (values
  ('oma-jamu',                 -8.6406125::double precision, 115.1433906::double precision),
  ('jungle-flower-restaurant', -8.5706125,                   115.2649219),
  ('gains',                    -8.8102375,                   115.1184219),
  ('humans-cafe',              -8.8190125,                   115.1601406),
  ('la-terrazza-uluwatu',      -8.8152625,                   115.0887031)
) as d(slug, lat, lng)
where v.slug = d.slug
  and v.status = 'active'
  and v.publication_status = 'published';


-- ── VERIFY ────────────────────────────────────────────────────────────
-- ожидается: 5
select count(*) from venues
where slug in ('oma-jamu','jungle-flower-restaurant','gains','humans-cafe','la-terrazza-uluwatu')
  and latitude is not null and longitude is not null;


