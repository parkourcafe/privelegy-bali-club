--
-- Решение основателя от 2026-08-04: брать координаты из сохранённых ссылок
-- Maps РАЗРЕШЕНО. Оно сняло оговорку по партии 1 и открыло этот путь.
--
-- Источник: Plus Code (Open Location Code), уже лежавший в собственных полях
-- записи — в venues.address у четырёх и в q=-параметре venues.gmaps_url,
-- привязанном к названию заведения, у oma-jamu. Сети для этого не нужно:
-- Plus Code — открытый стандарт, декодируется арифметикой.
--
-- Декодировано эталонной библиотекой `open-location-code`, а не своей
-- реализацией. Проверка библиотеки перед использованием: координата santanera
-- (из партии 1, взятая с сайта заведения) закодирована, укорочена и
-- восстановлена обратно — расхождение 2 метра.
--
-- Все пять кодов — короткие, 4 знака отброшены; восстановление однозначно в
-- пределах ±0.5° от опорной точки района, то есть на масштабе Бали
-- неоднозначности нет.

-- ── ПРОВЕРКА ──────────────────────────────────────────────────────────
-- Каждая точка проверена трижды, потому что рамки района недостаточно —
-- в партии 1 обе отклонённые координаты были ВНУТРИ рамки:
--
--   1. рамка района — все пять внутри;
--   2. клетка кода 3x3 м, то есть точность заведомо не грубее пятого знака;
--   3. декодированная точка совпадает с деревней, названной в том же
--      адресе — Pecatu, Ungasan, Lodtunduh, Suluban. Это проверка,
--      независимая от рамки.
--
-- slug                      lat          lng          деревня в адресе
-- oma-jamu                  -8.6406125   115.1433906  Canggu / Berawa
-- jungle-flower-restaurant  -8.5706125   115.2649219  Lodtunduh, Ubud
-- gains                     -8.8102375   115.1184219  Jl. Buana Sari, Pecatu
-- humans-cafe               -8.8190125   115.1601406  Jl. Bali Cliff, Ungasan
-- la-terrazza-uluwatu       -8.8152625   115.0887031  Pantai Suluban, Pecatu

-- ── DRY RUN — одна строка, откат ──────────────────────────────────────
-- Выполнено перед боевым прогоном: UPDATE 1, откат чистый.
-- begin;
-- update venues set latitude = -8.8102375, longitude = 115.1184219,
--   last_verified_at = '2026-08-04'
